import {
  DEVOPS_AREAS,
  FIT_BAND_LABELS,
  QUESTION_TYPE_LABELS,
  QUESTION_TYPES,
  gapsOf,
  type Requirement,
} from "../shared/report";
import { isDownloadable, type Analysis, type Session } from "./session";

// Builds the downloadable Markdown for a Report. Pure, so it runs (and is
// tested) without a DOM; the file is assembled in the browser, never on a server.

export interface ExportOptions {
  bookingUrl: string;
  includeChat?: boolean;
}

const EVIDENCE = { strong: "Strong", partial: "Partial", missing: "Missing" } as const;
const SENIORITY = { below: "Below the level", meets: "Meets the level", above: "Above the level" } as const;
const LEVEL = { low: "Low", medium: "Medium", high: "High" } as const;

const bullets = (items: string[], empty = "_None._") => (items.length ? items.map((i) => `- ${i}`).join("\n") : empty);

function requirementLine(r: Requirement): string {
  const lines = [`- **${EVIDENCE[r.evidence]}** · ${r.mustHave ? "Must-have" : "Nice-to-have"} · ${r.text}`];
  if (r.quote) lines.push(`  > ${r.quote}`);
  if (r.transfer) lines.push(`  _Transfers: ${r.transfer}_`);
  return lines.join("\n");
}

export function titleOf(a: Analysis): string {
  return a.report.extract?.job.title || "Job Description";
}

export function reportToMarkdown(a: Analysis, opts: ExportOptions): string {
  const { assess, plan, rewrites, interview } = a.report;
  const out: string[] = [`# Report: ${titleOf(a)}`];

  if (assess) {
    out.push(
      `## Fit Band: ${FIT_BAND_LABELS[assess.fitBand]}`,
      assess.reason,
      `### Seniority\n**${SENIORITY[assess.seniority.verdict]} (${assess.seniority.target}).** ${assess.seniority.notes}`,
      `### Hidden strengths\n${bullets(assess.hiddenStrengths)}`,
      `### Red flags a recruiter might notice\n${bullets(assess.redFlags)}`,
      `## Gaps`,
      gapsOf(assess.requirements).map(requirementLine).join("\n") || "_No Gaps: every requirement has strong evidence._",
      `### All requirements by area`,
      DEVOPS_AREAS.flatMap((area) => {
        const reqs = assess.requirements.filter((r) => r.area === area);
        return reqs.length ? [`#### ${area}\n${reqs.map(requirementLine).join("\n")}`] : [];
      }).join("\n\n"),
    );
  }

  if (plan) {
    out.push(
      `## Plan`,
      `**${plan.recommendation.decision === "apply_now" ? "Apply now" : "Prepare first"}.** ${plan.recommendation.reason}`,
      `### Close these Gaps, in this order`,
      plan.gaps
        .map((g, i) =>
          [
            `${i + 1}. **${g.requirement}** (${g.mustHave ? "Must-have" : "Nice-to-have"})`,
            `   Impact on getting hired: ${LEVEL[g.impact]} · Effort: ${LEVEL[g.effort]} · About ${g.timeEstimate}`,
            `   ${g.whatToLearn}`,
            `   Resources: ${g.resourceType}`,
            g.certification && `   Certification: ${g.certification}`,
          ]
            .filter(Boolean)
            .join("\n"),
        )
        .join("\n") || "_No Gaps to close._",
      `### Portfolio projects`,
      plan.projects
        .map((p) => `- **${p.title}**: ${p.description}${p.provesGaps.length ? ` _(Proves: ${p.provesGaps.join(", ")})_` : ""}`)
        .join("\n") || "_None suggested._",
    );
    if (plan.weeklyPlan.length) {
      out.push(`### Week by week`, plan.weeklyPlan.map((w) => `**Week ${w.week}: ${w.focus}**\n${bullets(w.tasks)}`).join("\n\n"));
    }
  }

  if (rewrites) {
    out.push(
      `## Resume suggestions`,
      `_AI-generated, check before use. Fill in any [placeholders] with your real figures, or remove them._`,
      `### Tailored summary\n${rewrites.summary}`,
      `### Stronger bullets`,
      rewrites.bullets.map((b) => `- Before: ${b.original}\n  After: ${b.rewritten}`).join("\n") || "_None suggested._",
      `### Keywords you can honestly add`,
      rewrites.missingKeywords.map((k) => `- **${k.keyword}**\n  > ${k.evidence}`).join("\n") || "_None._",
    );
  }

  if (interview) {
    out.push(`## Interview prep`);
    for (const type of QUESTION_TYPES) {
      const qs = interview.questions.filter((q) => q.type === type);
      if (!qs.length) continue;
      out.push(
        `### ${QUESTION_TYPE_LABELS[type]}`,
        qs
          .map((q, i) =>
            [`${i + 1}. **${q.question}**`, `   What they're testing: ${q.testing}`, ...q.resumeStories.map((s) => `   - ${s}`)].join("\n"),
          )
          .join("\n"),
      );
    }
  }

  if (opts.includeChat && a.chat.length) {
    out.push(`## Coaching Chat`, a.chat.map((t) => `**${t.role === "user" ? "You" : "Coach"}:** ${t.text}`).join("\n\n"));
  }

  if (opts.bookingUrl) out.push(`---\nWant help landing this role? [Book a session with Al](${opts.bookingUrl}).`);
  out.push(`_Generated by DevOps Career Coach. AI-generated advice: check it before you rely on it. This site kept no copy of your Report._`);
  return out.join("\n\n") + "\n";
}

export function sessionToMarkdown(s: Session, opts: ExportOptions): string {
  return reportsOf(s)
    .map((a) => reportToMarkdown(a, opts))
    .join("\n\n---\n\n");
}

// Analyses whose Report can be downloaded.
export function reportsOf(s: Session): Analysis[] {
  return s.analyses.filter(isDownloadable);
}

export function fileNameFor(title: string): string {
  const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);
  return `devops-coach-${slug || "report"}.md`;
}
